  citizenship: string;
  applicant_type: string;
  intake: string;
  major: string;
  countries: string[];
  country_locks: string[];
  geography_flexible: boolean;
  financial_flexibility: boolean;
  budget_hard: boolean;
  curriculum: string;
  raw_grade: string;
  raw_scale: string;
  ib_total: number | null;
