export type Evidence = 'VERIFIED' | 'PARTIAL' | 'STALE' | 'CONFLICTING' | 'UNKNOWN';
export type State =
  'READY_TO_APPLY' | 'WITHIN_REACH' | 'CONDITIONAL_PATH' | 'BLOCKED' | 'INDETERMINATE';
export type Verdict = 'PASS' | 'FAIL' | 'UNKNOWN' | 'NOT_APPLICABLE';
export type CostState = 'WITHIN_BUDGET' | 'OVER_BUDGET' | 'UNKNOWN';
export type Timeline = 'FEASIBLE' | 'TIGHT' | 'MISSED' | 'UNKNOWN';
export type Fact = {
  id: string;
  field: string;
  value: unknown;
  statement: string;
  source_url: string | null;
  page_title: string | null;
  retrieved_at: string;
  intake: string;
  scope: Record<string, string>;
  evidence: Evidence;
  provenance: 'OFFICIAL_FACT' | 'UNKNOWN' | 'PRODUCT_ASSUMPTION' | 'PATHSHIFT_INFERENCE';
  notes: string;
};
export type Rule = {
  id: string;
  label: string;
  op: 'ATOM' | 'ALL' | 'ANY_OF' | 'EXEMPTION' | 'CONDITIONAL_PATH' | 'POST_ENROLMENT';
  strength: 'HARD' | 'SOFT' | 'INFO';
  facts: string[];
  field?: string;
  comparator?: 'EQ' | 'NEQ' | 'GTE' | 'LTE' | 'PRESENT' | 'IN' | 'BEFORE' | 'AFTER' | 'SATISFIES';
  value?: unknown;
  valueKey?: string;
  unknown?: boolean;
  children?: Rule[];
  requirement?: Rule;
  exemption?: Rule;
  direct?: Rule;
  alternative?: Rule;
  action?: string;
  immutable?: boolean;
};
export type Deadline = {
  type: string;
  plan: string;
  date: string;
  time: string | null;
  timezone: string | null;
  fact: string;
};
export type Program = {
  id: string;
  name: string;
  short: string;
  degree: string;
  country: string;
  city: string;
  initials: string;
  color: string;
  structure: string;
  tags: string[];
  rules: Rule[];
  deadlines: Deadline[];
  cost?: {
    min: number;
    max: number;
    currency: 'USD' | 'CAD' | 'GBP';
    year: string;
    complete: boolean;
    fact: string;
  };
  conditional?: { name: string; fact: string; note: string };
};
